import { createFileRoute, Link } from "@tanstack/react-router";
import { ArrowRight, Compass, HelpCircle, ListChecks } from "lucide-react";
import { useState } from "react";
import { field } from "@/components/EnquiryForm";
import { Page, PageHero, RiskNotice, seo } from "@/components/SiteShell";
import { getService } from "@/lib/services";

const crumbs = [{ name: "AI Funding Advisor", path: "/funding-advisor" }];

export const Route = createFileRoute("/funding-advisor")({
  head: ({ matches }) => seo({ matches,
    title: "AI Funding Advisor | Find the Right Business Finance | FundingCompany",
    description: "Describe your business, how much you need and why. Our AI-powered advisor suggests relevant UK funding options, explains what lenders consider and what to ask.",
    path: "/funding-advisor",
    crumbs,
  }),
  component: Advisor,
});

type Result = {
  summary: string;
  recommendations: { slug: string; reason: string }[];
  lender_factors: { factor: string; explanation: string }[];
  questions_to_ask: string[];
};

function Advisor() {
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const [result, setResult] = useState<Result | null>(null);
  const [form, setForm] = useState({ needs: "", amount: "", situation: "" });

  async function run(e: React.FormEvent) {
    e.preventDefault();
    if (form.needs.trim().length < 10) { setError("Please describe what you need funding for in a little more detail."); return; }
    setLoading(true); setError(null); setResult(null);
    try {
      const res = await fetch("/api/advisor", { method: "POST", headers: { "Content-Type": "application/json" }, body: JSON.stringify(form) });
      const json = await res.json();
      if (!res.ok) throw new Error(json.error ?? "Something went wrong.");
      setResult(json);
    } catch (err) {
      setError(err instanceof Error ? err.message : "Something went wrong.");
    } finally {
      setLoading(false);
    }
  }

  return (
    <Page>
      <PageHero eyebrow="AI-powered" title="AI Funding Advisor" intro="Tell us what you need, how much and a little about your business. We'll suggest funding routes worth exploring, what lenders may look at, and questions to ask." crumbs={crumbs} />
      <section className="container-x grid gap-10 py-16 lg:grid-cols-[1fr_1.2fr]">
        <form onSubmit={run} className="space-y-4 self-start rounded-3xl border bg-card p-8 shadow-xl">
          <label className="block text-sm font-medium">What do you need funding for? *
            <textarea rows={4} value={form.needs} onChange={(e) => setForm({ ...form, needs: e.target.value })} maxLength={2000} placeholder="e.g. We need a new delivery van and extra stock ahead of Christmas." className={`${field} mt-1`} />
          </label>
          <label className="block text-sm font-medium">Desired amount
            <input value={form.amount} onChange={(e) => setForm({ ...form, amount: e.target.value })} maxLength={60} placeholder="e.g. £40,000" className={`${field} mt-1`} />
          </label>
          <label className="block text-sm font-medium">Your business situation
            <textarea rows={4} value={form.situation} onChange={(e) => setForm({ ...form, situation: e.target.value })} maxLength={2000} placeholder="e.g. Limited company, trading 3 years, £600k turnover, one missed payment last year." className={`${field} mt-1`} />
          </label>
          {error && <p role="alert" className="text-sm text-destructive">{error}</p>}
          <button disabled={loading} className="btn-primary w-full disabled:opacity-60">{loading ? "Thinking…" : "Get my funding suggestions"}</button>
          <p className="text-xs text-muted-foreground">Please don't include bank details or passwords. Suggestions are generated by AI, are general information only and are not financial advice or an offer of finance.</p>
        </form>

        <div className="space-y-6" aria-live="polite">
          {loading && <div className="animate-pulse rounded-3xl border bg-card p-8 text-muted-foreground">Reviewing your situation and matching funding routes…</div>}
          {!loading && !result && (
            <div className="rounded-3xl border border-dashed p-8 text-muted-foreground">Your personalised suggestions will appear here.</div>
          )}
          {result && (
            <>
              <div className="hero-glow rounded-3xl p-8"><p className="eyebrow !text-accent">Summary</p><p className="mt-2 text-lg">{result.summary}</p></div>
              <div className="rounded-3xl border bg-card p-8">
                <h2 className="flex items-center gap-2 text-2xl font-semibold"><Compass className="h-6 w-6 text-signal" />Funding options to explore</h2>
                <div className="mt-5 grid gap-3">
                  {result.recommendations.map((r) => {
                    const s = getService(r.slug);
                    if (!s) return null;
                    return (
                      <Link key={r.slug} to="/$slug" params={{ slug: r.slug }} className="group rounded-2xl border p-5 transition hover:border-signal">
                        <p className="flex items-center justify-between font-semibold">{s.name}<ArrowRight className="h-4 w-4 text-signal transition group-hover:translate-x-1" /></p>
                        <p className="mt-1 text-sm text-muted-foreground">{r.reason}</p>
                      </Link>
                    );
                  })}
                </div>
              </div>
              <div className="rounded-3xl border bg-card p-8">
                <h2 className="flex items-center gap-2 text-2xl font-semibold"><ListChecks className="h-6 w-6 text-signal" />What lenders may consider</h2>
                <dl className="mt-5 space-y-4">{result.lender_factors.map((f) => <div key={f.factor}><dt className="font-semibold">{f.factor}</dt><dd className="text-sm text-muted-foreground">{f.explanation}</dd></div>)}</dl>
              </div>
              <div className="rounded-3xl border bg-card p-8">
                <h2 className="flex items-center gap-2 text-2xl font-semibold"><HelpCircle className="h-6 w-6 text-signal" />Questions to ask lenders</h2>
                <ol className="mt-5 list-decimal space-y-2 pl-5 text-muted-foreground">{result.questions_to_ask.map((q) => <li key={q}>{q}</li>)}</ol>
              </div>
              <div className="flex flex-wrap gap-3"><Link to="/contact" className="btn-primary">Talk to us about these options</Link></div>
            </>
          )}
          <RiskNotice variant="compact" />
        </div>
      </section>
    </Page>
  );
}
